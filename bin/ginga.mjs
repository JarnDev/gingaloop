#!/usr/bin/env node
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import * as cli from "../src/cli.mjs";
import { COMMAND_HELP } from "../src/help.mjs";
import { paint } from "../src/view.mjs";
import { PKG_ROOT, UserError } from "../src/workspace.mjs";

const HELP = `gingaloop: daily coding challenges generated by Claude, tested in a sandbox.

Usage: ginga <command> [args] [--workspace DIR]

Setup
  init [dir]                 create a workspace (asks for rotation + time)
  doctor [--pull|--prune [--all]]   check setup; pre-pull images, or remove stale built ones
  config [get|set|unset <key> [value]]   view or change gingaloop.json (model, budget, editor…)
  completion bash|zsh        shell completion: source <(ginga completion zsh)
  rotation [list|set|add|remove <langs> | mode random|ordered | anchor … | extra …]   the daily's languages, order, anchors, extras
  stack [<lang> basics|mixed|ecosystem]   standard library only, or also pinned libraries (pandas…)
  domains [list|set|add|remove <ids>]     industries your challenges are framed in (general by default)
  lang list | add <name>     list profiles / bootstrap a new language with Claude
  schedule install|remove|status [--time HH:MM]   systemd user timer for \`daily\`

Practice
  new <lang> [--level N] [--area ID] [--stack S] [--type T] [--domain D]   generate a challenge now (N ≤ your earned level)
  daily [--force]            today's challenges from the rotation (used by the timer)
  open [id]                  open README + starter in $EDITOR, inside the challenge folder
  test [id] [--watch]        run the tests against your starter/ (sandboxed); --watch reruns on save
  pause [id] / resume [id]   pause the challenge's timer for a break, start it again
  timer [id]                 the timer: running or paused, active minutes, pauses
  hint [id]                  reveal the next hint (recorded)
  done [id] [--minutes N]    verify tests pass, record the solve, unlock the solution
  giveup [id] [--reason R]   record a give-up (and what stopped you), unlock the solution
  discard [id] [--reason R]  drop a broken or unwanted challenge: no penalty, no reveal, not counted
  review [id]                ask Claude to review your solution (after unlock)
  learn [id] [--report]      turn a review's findings about the challenge into rules for future ones

Progress
  rank [--json]              levels, progress to next level, streak, weak topics, Claude cost
  coverage [lang…] [--json]  practice areas per language and how often you've had each
  list [--json]              all challenges with status

Workspace repo (plain git, no Claude tokens)
  commit [--yes] [--push]    commit the workspace with a message built from your progress
  push                       push the workspace (sets the upstream on the first push)

Authoring
  validate [dir] [--examples]  solution passes, starter fails, every bug caught
  sandbox run --lang L [--dir D] [--cwd C] [--target T] [--impl I --tests S] -- <cmd>

[id] defaults to your newest open challenge. \`ginga <command> --help\` (or \`ginga help <command>\`) for details.
Only daily, new, lang add, review and learn use Claude (tokens); everything else is local. Docs: README.md`;

const commands = {
  init: cli.cmdInit, new: cli.cmdNew, daily: cli.cmdDaily, test: cli.cmdTest, hint: cli.cmdHint,
  done: cli.cmdDone, giveup: cli.cmdGiveup, discard: cli.cmdDiscard, rank: cli.cmdRank, list: cli.cmdList,
  validate: cli.cmdValidate, sandbox: cli.cmdSandbox, lang: cli.cmdLang, rotation: cli.cmdRotation, stack: cli.cmdStack, domains: cli.cmdDomains, coverage: cli.cmdCoverage, open: cli.cmdOpen, pause: cli.cmdPause, resume: cli.cmdResume, timer: cli.cmdTimer, schedule: cli.cmdSchedule,
  doctor: cli.cmdDoctor, review: cli.cmdReview, learn: cli.cmdLearn, commit: cli.cmdCommit, push: cli.cmdPush, config: cli.cmdConfig, completion: cli.cmdCompletion,
};

const { values, positionals, tokens } = parseArgs({
  allowPositionals: true,
  strict: true,
  tokens: true,
  options: {
    workspace: { type: "string", short: "w" },
    level: { type: "string", short: "l" },
    area: { type: "string" },
    stack: { type: "string" },
    type: { type: "string" },
    domain: { type: "string" },
    domains: { type: "string" },
    minutes: { type: "string" },
    reason: { type: "string" },
    json: { type: "boolean" },
    watch: { type: "boolean" },
    prune: { type: "boolean" },
    all: { type: "boolean" },
    yes: { type: "boolean", short: "y" },
    force: { type: "boolean" },
    examples: { type: "boolean" },
    pull: { type: "boolean" },
    rotation: { type: "string" },
    mode: { type: "string" },
    time: { type: "string" },
    engine: { type: "string" },
    lang: { type: "string" },
    dir: { type: "string" },
    cwd: { type: "string" },
    target: { type: "string" },
    impl: { type: "string" },
    tests: { type: "string" },
    "profile-file": { type: "string" },
    jail: { type: "boolean" },
    push: { type: "boolean" },
    report: { type: "boolean" },
    default: { type: "boolean" },
    help: { type: "boolean", short: "h" },
    version: { type: "boolean", short: "v" },
  },
});

// Each option at most once: with "last one wins", an appended `--dir /` could silently widen a
// command that was granted with a fixed prefix (see `sandbox run --jail`).
const seen = new Set();
for (const t of tokens) {
  if (t.kind !== "option") continue;
  if (seen.has(t.name)) {
    console.error(`ginga: option --${t.name} was given more than once`);
    process.exit(2);
  }
  seen.add(t.name);
}

const [name, ...rest] = positionals;
const helpFor = name === "help" ? rest[0] : values.help ? name : undefined;
if (values.version) {
  console.log(JSON.parse(readFileSync(join(PKG_ROOT, "package.json"), "utf8")).version);
} else if (helpFor && COMMAND_HELP[helpFor]) {
  console.log(COMMAND_HELP[helpFor]);
} else if (!name || name === "help" || values.help) {
  console.log(HELP);
  if (helpFor) process.exitCode = 2;
} else if (!commands[name]) {
  console.error(`ginga: unknown command "${name}". Run \`ginga --help\` for the list.`);
  process.exitCode = 2;
} else {
  try {
    await commands[name](rest, values);
  } catch (e) {
    if (e instanceof UserError) {
      console.error(`${paint.red("ginga:", process.stderr)} ${e.message}`);
      process.exitCode = 1;
    } else {
      throw e;
    }
  }
}

#!/usr/bin/env node
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import * as cli from "../src/cli.mjs";
import { PKG_ROOT, UserError } from "../src/workspace.mjs";

const HELP = `gingaloop: daily coding challenges generated by Claude, tested in a sandbox.

Usage: ginga <command> [args] [--workspace DIR]

Setup
  init [dir]                 create a workspace (asks for rotation + time)
  doctor [--pull]            check claude, docker/podman and language images
  rotation [list|set|add|remove <langs> | mode random|ordered]   the daily's languages and order
  lang list | add <name>     list profiles / bootstrap a new language with Claude
  schedule install|remove|status [--time HH:MM]   systemd user timer for \`daily\`

Practice
  new <lang> [--level N] [--area ID]   generate a challenge now (N ≤ your earned level)
  daily [--force]            today's challenge from the rotation (used by the timer)
  open [id]                  open README + starter in $EDITOR, inside the challenge folder
  test [id]                  run the tests against your starter/ (sandboxed)
  hint [id]                  reveal the next hint (recorded)
  done [id] [--minutes N]    verify tests pass, record the solve, unlock the solution
  giveup [id] [--yes]        record a give-up and unlock the solution
  review [id]                ask Claude to review your solution (after unlock)

Progress
  rank                       levels, progress to next level, streak, weak topics
  coverage [lang…]           practice areas per language and how often you've had each
  list                       all challenges with status

Authoring
  validate [dir] [--examples]  solution passes, starter fails, every bug caught
  sandbox run --lang L [--dir D] [--cwd C] [--target T] -- <cmd>

[id] defaults to your newest open challenge. Docs: README.md`;

const commands = {
  init: cli.cmdInit, new: cli.cmdNew, daily: cli.cmdDaily, test: cli.cmdTest, hint: cli.cmdHint,
  done: cli.cmdDone, giveup: cli.cmdGiveup, rank: cli.cmdRank, list: cli.cmdList,
  validate: cli.cmdValidate, sandbox: cli.cmdSandbox, lang: cli.cmdLang, rotation: cli.cmdRotation, coverage: cli.cmdCoverage, open: cli.cmdOpen, schedule: cli.cmdSchedule,
  doctor: cli.cmdDoctor, review: cli.cmdReview,
};

const { values, positionals } = parseArgs({
  allowPositionals: true,
  strict: true,
  options: {
    workspace: { type: "string", short: "w" },
    level: { type: "string", short: "l" },
    area: { type: "string" },
    minutes: { type: "string" },
    yes: { type: "boolean", short: "y" },
    force: { type: "boolean" },
    examples: { type: "boolean" },
    pull: { type: "boolean" },
    rotation: { type: "string" },
    mode: { type: "string" },
    time: { type: "string" },
    engine: { type: "string" },
    lang: { type: "string" },
    dir: { type: "string" },
    cwd: { type: "string" },
    target: { type: "string" },
    "profile-file": { type: "string" },
    help: { type: "boolean", short: "h" },
    version: { type: "boolean", short: "v" },
  },
});

const [name, ...rest] = positionals;
if (values.version) {
  console.log(JSON.parse(readFileSync(join(PKG_ROOT, "package.json"), "utf8")).version);
} else if (!name || values.help || !commands[name]) {
  console.log(HELP);
  if (name && !commands[name]) process.exitCode = 2;
} else {
  try {
    await commands[name](rest, values);
  } catch (e) {
    if (e instanceof UserError) {
      console.error(`ginga: ${e.message}`);
      process.exitCode = 1;
    } else {
      throw e;
    }
  }
}
